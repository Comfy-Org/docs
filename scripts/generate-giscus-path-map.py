#!/usr/bin/env python3
"""Regenerate the GISCUS_PATH_MAP embedded in giscus-comments.js.

Why: giscus pathname+strict matching relies on GitHub Discussion search.
That index is incomplete for Comfy-Org/docs, so many existing threads never
appear on their docs pages (#1468). Looking up discussions by number bypasses
search. This script lists Announcements discussions via GraphQL (not search)
and rewrites the map in giscus-comments.js.

Usage (requires gh auth with repo read):
  python3 scripts/generate-giscus-path-map.py
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JS_PATH = ROOT / "giscus-comments.js"
MARKER_START = "  // <giscus-path-map>"
MARKER_END = "  // </giscus-path-map>"


def gh_graphql(query: str, **variables):
    args = ["gh", "api", "graphql", "-f", f"query={query}"]
    for key, value in variables.items():
        args.extend(["-F", f"{key}={value}"])
    return json.loads(subprocess.check_output(args, text=True))


def fetch_announcement_discussions():
    nodes = []
    cursor = None
    while True:
        if cursor is None:
            data = gh_graphql(
                """
                query {
                  repository(owner: "Comfy-Org", name: "docs") {
                    discussions(first: 100) {
                      pageInfo { hasNextPage endCursor }
                      nodes {
                        number
                        title
                        category { name }
                        comments { totalCount }
                      }
                    }
                  }
                }
                """
            )
        else:
            data = gh_graphql(
                """
                query ($c: String!) {
                  repository(owner: "Comfy-Org", name: "docs") {
                    discussions(first: 100, after: $c) {
                      pageInfo { hasNextPage endCursor }
                      nodes {
                        number
                        title
                        category { name }
                        comments { totalCount }
                      }
                    }
                  }
                }
                """,
                c=cursor,
            )
        page = data["data"]["repository"]["discussions"]
        nodes.extend(page["nodes"])
        if not page["pageInfo"]["hasNextPage"]:
            break
        cursor = page["pageInfo"]["endCursor"]

    return [
        n
        for n in nodes
        if n["category"]["name"] == "Announcements"
    ]


def build_path_map(discussions):
    by_title = defaultdict(list)
    for node in discussions:
        title = (node["title"] or "").strip()
        if not title or title == "Welcome to docs Discussions!":
            continue
        # Pathname-style titles only (giscus creates these)
        if " " in title and "/" not in title:
            continue
        by_title[title].append(node)

    path_map = {}
    for title, items in by_title.items():
        items = sorted(
            items,
            key=lambda item: (-item["comments"]["totalCount"], item["number"]),
        )
        path_map[title] = items[0]["number"]

    # Site locale is /zh/...; older threads used zh-CN/...
    for title, number in list(path_map.items()):
        if title.startswith("zh-CN/"):
            alias = "zh/" + title[len("zh-CN/") :]
            path_map.setdefault(alias, number)

    return path_map


def render_map_block(path_map: dict[str, int]) -> str:
    entries = ",\n".join(
        f"    {json.dumps(key)}: {number}"
        for key, number in sorted(path_map.items())
    )
    return (
        f"{MARKER_START}\n"
        "  // Auto-generated by scripts/generate-giscus-path-map.py — do not edit by hand.\n"
        "  // Maps docs pathname (no leading slash) -> GitHub Discussion number.\n"
        '  // Used with giscus data-mapping="number" to bypass broken GitHub discussion search.\n'
        "  const GISCUS_PATH_MAP = {\n"
        f"{entries}\n"
        "  };\n"
        f"{MARKER_END}\n"
    )


def main() -> int:
    if not JS_PATH.exists():
        print(f"missing {JS_PATH}", file=sys.stderr)
        return 1

    discussions = fetch_announcement_discussions()
    path_map = build_path_map(discussions)
    block = render_map_block(path_map)

    text = JS_PATH.read_text()
    if MARKER_START not in text or MARKER_END not in text:
        print("giscus-comments.js is missing path-map markers", file=sys.stderr)
        return 1

    pattern = re.compile(
        re.escape(MARKER_START) + r"[\s\S]*?" + re.escape(MARKER_END) + r"\n"
    )
    new_text, count = pattern.subn(block, text, count=1)
    if count != 1:
        print("failed to rewrite path-map block", file=sys.stderr)
        return 1

    JS_PATH.write_text(new_text)
    print(f"Wrote {len(path_map)} path mappings into {JS_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
